-- -------------------------------------------------------------
-- 1. The "properties" table
--    Column names match the fields used in the React app.
-- -------------------------------------------------------------
create table if not exists public.properties (
  id           bigint generated by default as identity primary key,
  title        text          not null,
  location     text          not null,
  price        numeric       not null,
  type         text          not null, -- Apartment | Villa | Independent House | Studio | Plot
  listing_type text          not null, -- Buy | Rent
  bedrooms     integer,
  bathrooms    integer,
  area         numeric,                -- size in square feet
  description  text,
  image_url    text,
  created_at   timestamptz   not null default now()
);

-- -------------------------------------------------------------
-- 2. Row Level Security
--    We keep this simple: everyone can READ, nobody can write
--    from the website. (Writes are done by you, in this editor.)
-- -------------------------------------------------------------
alter table public.properties enable row level security;

drop policy if exists "Public can read properties" on public.properties;

create policy "Public can read properties"
  on public.properties
  for select
  to anon, authenticated
  using (true);

